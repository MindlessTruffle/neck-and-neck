import assert from 'node:assert/strict';
import { steerLook, cameraRelativeMovement, stickMovement, applyWalk } from '../src/controls.js';
const view = { yaw: 0, pitch: 0 }, neck = { yaw: 0, pitch: .15 };
steerLook(view, neck, 100, -50);
assert.ok(view.yaw > 0 && view.pitch > 0, 'Mouse steers the neck and desired follow heading');
assert.equal(neck.yaw, view.yaw, 'Camera target follows the mouse-driven neck target');
const yaw = neck.yaw;
steerLook(view, neck, -100, 80);
assert.ok(neck.yaw < yaw, 'Reverse mouse sweep reverses the neck target without a mode switch');
assert.equal(view.yaw, neck.yaw);
steerLook(view, neck, 0, -100000); assert.equal(view.pitch, .3);
steerLook(view, neck, 0, 100000); assert.equal(view.pitch, -.2);
const forward = cameraRelativeMovement(1, 0, Math.PI / 2);
assert.ok(Math.abs(forward.x) < 1e-10 && Math.abs(forward.z - 1) < 1e-10);
const diagonal = cameraRelativeMovement(1, 1, .7);
assert.ok(Math.abs(Math.hypot(diagonal.x, diagonal.z) - 1) < 1e-10, 'Diagonal input has no speed advantage');
assert.deepEqual(stickMovement(2, 2), { x: 0, z: 0 });
const stick = stickMovement(200, -200);
assert.ok(Math.abs(Math.hypot(stick.x, stick.z) - 1) < 1e-10);
assert.ok(stick.x > 0 && stick.z < 0);
const movement = { walk: { x: 0, z: 0 }, walkOwner: null };
applyWalk(movement, { x: 1, z: 0 }, 'stick:1');
applyWalk(movement, { x: 0, z: -1 }, 'canvas:2');
assert.deepEqual(movement.walk, { x: 1, z: 0 }, 'Second finger cannot steal held joystick');
applyWalk(movement, { x: 0, z: 0 }, 'canvas:2');
assert.equal(movement.walk.x, 1, 'Unrelated finger release cannot cancel held movement');
applyWalk(movement, { x: 0, z: 0 }, 'stick:1');
assert.equal(movement.walkOwner, null, 'Capture loss/release clears the owning pointer');
applyWalk(movement, { x: 0, z: -1 }, 'canvas:2');
assert.equal(movement.walk.z, -1);
console.log('PASS controls: mouse-driven neck target, reverse swings without modifiers, safe pitch limits, camera-relative movement, multi-pointer joystick ownership.');

